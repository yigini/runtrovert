function since(days: number): string {
  if (days < 21) return Math.round(days / 7) === 1 ? 'une semaine' : `${days} jours`;
  if (days < 60) return `${Math.round(days / 7)} semaines`;
  return `${Math.round(days / 30)} mois`;
}

