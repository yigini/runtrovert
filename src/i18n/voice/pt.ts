function since(days: number): string {
  if (days < 21) return Math.round(days / 7) === 1 ? 'uma semana' : `${days} dias`;
  if (days < 60) return `${Math.round(days / 7)} semanas`;
  return `${Math.round(days / 30)} meses`;
}

