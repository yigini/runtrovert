function since(days: number): string {
  if (days < 21) return Math.round(days / 7) === 1 ? 'una settimana' : `${days} giorni`;
  if (days < 60) return `${Math.round(days / 7)} settimane`;
  return `${Math.round(days / 30)} mesi`;
}

