function gapWords(days: number): string {
  if (days < 21) return Math.round(days / 7) === 1 ? 'bir hafta' : `${days} gün`;
  if (days < 60) return `${Math.round(days / 7)} hafta`;
  return `${Math.round(days / 30)} ay`;
}

